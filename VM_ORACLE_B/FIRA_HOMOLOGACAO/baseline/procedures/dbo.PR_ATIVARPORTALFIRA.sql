CREATE PROCEDURE [dbo].[PR_ATIVARPORTALFIRA]
(
    @PRODUCTKEY VARCHAR(1000), @EXPIRATIONDATE INT
)--WITH ENCRYPTION
AS
BEGIN
    IF NOT EXISTS (SELECT Chave,DataVencimento,dt_fira FROM ATIVACAOPORTALFIRA)
	BEGIN
    INSERT INTO ATIVACAOPORTALFIRA
    VALUES(@PRODUCTKEY, @EXPIRATIONDATE,GETDATE())
	END
	ELSE
	BEGIN
    UPDATE ATIVACAOPORTALFIRA 
	SET CHAVE = @PRODUCTKEY,
	DATAVENCIMENTO = @EXPIRATIONDATE
	END
END