AS

IF NOT EXISTS (SELECT * FROM sys.objects WHERE object_id = OBJECT_ID(N'[dbo].[ST_DADOS_BASICOS_PJ_PADRAO]') AND type in (N'U'))
CREATE TABLE [dbo].[ST_DADOS_BASICOS_PJ_PADRAO](
	[NM_CLIENTE] [varchar](160) NOT NULL,
	[CD_CLIENTE] [int] NOT NULL,
	[CD_CPFCGC] [varchar](20) NOT NULL,
	[DT_CRIACAO] [datetime2](7) NOT NULL,
	[DT_ATUALIZ] [datetime2](7) NULL,
	[NM_LOGRADOURO] [nvarchar](max) NULL,
	[NR_PREDIO] [varchar](5) NULL,
	[NM_COMP_ENDE] [varchar](110) NULL,
	[NM_BAIRRO] [varchar](118) NULL,
	[NM_CIDADE] [varchar](128) NULL,
	[SG_ESTADO] [varchar](4) NULL,
	[SG_PAIS] [varchar](10) NULL,
	[NM_E_MAIL] [varchar](255) NULL,
	[IN_PESS_VINC] [char](1) NULL,
	[DT_NASC_FUND] [datetime2](7) NULL,
	[DS_TIPO_CLIENTE] [varchar](40) NULL,
	[NR_TELEFONE] [nvarchar](400) NULL,
	[EMAIL_SEQ] [nvarchar](384) NULL,
	[ENDE_SEQ] [nvarchar](384) NULL,
	[NM_EMIT_ORDEM] [varchar](130) NULL,
	[CD_CPFCGC_EMIT] [varchar](20) NULL,
	[CD_DOC_IDENT_EMIT] [varchar](16) NULL,
	[EMISSOR_PRINCIPAL] [char](1) NULL,
	[CD_SISTEMA] [varchar](4) NULL,
	[CD_ASSESSOR] [numeric](15, 0) NULL,
	[CD_CON_DEP] [int] NULL,
	[DS_CON_DEP] [varchar](50) NULL,
	[IN_CONTA_INV] [char](1) NULL,
	[IN_SITUAC] [char](1) NULL,
	[cd_Cep] [varchar](15) NULL,
	[CD_DDD_TEL] [int] NULL,
	[TP_SITUAC] [varchar](15) NULL,
	[nm_grupo] [varchar](30) NULL,
	[CD_DDD_FAX] [int] NULL,
	[NR_DDD_FAX] [int] NULL,
	[NM_ASSESSOR] [varchar](100) NULL,
	[VL_OPERACIONAL1] [float] NULL,
	[VL_OPERACIONAL2] [float] NULL,
	[VL_OPERACIONAL3] [float] NULL,
	[VL_CAPACIDADE_FIN] [float] NULL,
	[DT_ATUALIZ_SALARIO] [smalldatetime] NULL,
	[TP_CLIENTE] [int] NULL,
	[NM_RESU_ASSES] [varchar](100) NULL,
	[in_politico_exp] [char](1) NULL,
	[IN_PROCUR] [varchar](2) NULL,
	[IN_PRINCIPAL] [varchar](2) NULL,
