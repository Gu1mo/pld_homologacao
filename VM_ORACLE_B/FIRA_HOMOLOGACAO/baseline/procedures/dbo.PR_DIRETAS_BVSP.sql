	@INICIO DATETIME,		
	@FIM DATETIME,		
    @CD_CLIENTE_COMPRA VARCHAR(160),		
    @CD_CLIENTE_VENDA VARCHAR(160),
	@QTDPORPAGINA INT, @PAGINA INT
		
		
    --@CD_ASSESSOR_COMPRA VARCHAR(10),		
    --@CD_ASSESSOR_VENDA VARCHAR(10),		
    --@VINCULADO_COMPRA CHAR(01),		
    --@VINCULADO_VENDA CHAR(01),		
    --@CD_PAPEL VARCHAR(10),		
    --@TP_CLIENTE_COMPRA INT,		
    --@TP_CLIENTE_VENDA INT		
)		--WITH ENCRYPTION
		
AS		
