 --        WHEN A.ITEM = 'SWING_BMF'		THEN 'SWING_BMF'  
 --        WHEN A.ITEM = 'DAYTRADE_BOVESPA_01'		THEN 'DAYTRADE_BOVESPA_01'   
 --        WHEN A.ITEM = 'DAYTRADE_BMF_01'			THEN 'DAYTRADE_BMF_01'    
 --        WHEN A.ITEM = 'MUDANCA_REPENTINA'		THEN 'MUDANCA_REPENTINA'  
 --        WHEN A.ITEM = 'MEDIA_BOVESPA_01'			THEN 'MEDIA_BOVESPA_01'   
 --        WHEN A.ITEM = 'MEDIA_BMF_01'				THEN 'MEDIA_BMF_01' 
 --        WHEN A.ITEM = 'AML_BOVESPA'			THEN 'AML_BOVESPA'  
 --        WHEN A.ITEM = 'AML_BMF'				THEN 'AML_BMF' 
	--	 WHEN A.ITEM = 'AML_CORRETORA_BOVESPA'			THEN 'AML_CORRETORA_BOVESPA'  
 --        WHEN A.ITEM = 'AML_CORRETORA_BMF'				THEN 'AML_CORRETORA_BMF' 
