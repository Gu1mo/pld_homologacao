        SELECT @DEFAULT AS PATRIMONIO_CUSTODIA,@DEFAULT AS PATRIMONIO_MOVCC,@DEFAULT AS PATRIMONIO_NETTING,@DEFAULT AS PATRIMONIO_TRANSF_CUST, @DEFAULT AS SWING_BOVESPA,
