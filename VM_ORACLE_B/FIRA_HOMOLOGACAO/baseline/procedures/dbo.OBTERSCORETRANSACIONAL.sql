			CASE WHEN ATUALIZACAO_CADASTRAL IS NULL THEN @DEFAULT ELSE ATUALIZACAO_CADASTRAL END AS ATUALIZACAO_CADASTRAL
		FROM
		(
			SELECT PESO, ITEM
			FROM PORTALCONFIGSCORE WHERE IDUSUARIO = @USUARIO
		) D
		PIVOT
		(
			MAX(PESO)
			FOR ITEM IN ( PATRIMONIO_CUSTODIA,PATRIMONIO_MOVCC,PATRIMONIO_NETTING,PATRIMONIO_TRANSF_CUST,CHURNING_01,
							SWING_BOVESPA, SWING_BMF, DAYTRADE_BOVESPA_01, DAYTRADE_BMF_01, MUDANCA_REPENTINA,PROCURADOR,ATUALIZACAO_CADASTRAL,
							MEDIA_BOVESPA_01, MEDIA_BMF_01, AML_BOVESPA, AML_BMF, AML_CORRETORA_BOVESPA, AML_CORRETORA_BMF, OMC_BOVESPA,OMC_BMF,
							INSIDER_TRADING_BOVESPA, LAYERING_01, SPOOFING_01, TRANSFERENCIA_FINANCEIRA_01, TRANSFERENCIA_FINANCEIRA_02)
		) PIV;
	END

	 

