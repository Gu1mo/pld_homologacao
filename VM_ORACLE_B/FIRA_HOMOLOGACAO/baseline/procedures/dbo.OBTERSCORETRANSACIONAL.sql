			CASE WHEN OMC_BOVESPA IS NULL THEN @DEFAULT ELSE OMC_BOVESPA END AS OMC_BOVESPA,
			CASE WHEN INSIDER_TRADING_BOVESPA IS NULL THEN @DEFAULT ELSE INSIDER_TRADING_BOVESPA END AS INSIDER_TRADING_BOVESPA,
			CASE WHEN OMC_BMF IS NULL THEN @DEFAULT ELSE OMC_BMF END AS OMC_BMF,
			CASE WHEN LAYERING_01 IS NULL THEN @DEFAULT ELSE LAYERING_01 END AS LAYERING_01,
			CASE WHEN SPOOFING_01 IS NULL THEN @DEFAULT ELSE SPOOFING_01 END AS SPOOFING_01,
			CASE WHEN CHURNING_01 IS NULL THEN @DEFAULT ELSE CHURNING_01 END AS CHURNING_01,
			CASE WHEN TRANSFERENCIA_FINANCEIRA_01 IS NULL THEN @DEFAULT ELSE TRANSFERENCIA_FINANCEIRA_01 END AS TRANSFERENCIA_FINANCEIRA_01,
			CASE WHEN TRANSFERENCIA_FINANCEIRA_02 IS NULL THEN @DEFAULT ELSE TRANSFERENCIA_FINANCEIRA_02 END AS TRANSFERENCIA_FINANCEIRA_02,
