		WHERE A.DT_PERIODO >= B.DT_PRE AND A.DT_PERIODO < B.DT_FATO  --periodo comparativo
		AND CD_NATOPE = 'C'
		
	 GROUP BY CD_CLIENTE
			, A.CD_PAPEL
			, B.DT_POS
			, B.DT_FATO
			, B.DT_COMP
			, B.DT_PRE
