DROP TABLE IF EXISTS #FATO_CLI;


	  SELECT A.ATIVO 
		   , A.CD_PAPEL 
		   , A.DT_COMP
		   , B.DT_PRE
		   , A.DT_FATO 
		   , C.DT_POS
		   , D.EMPRESA 
		  , D.FATO_RELEVANTEATIVO
		  , A.AVG_INTERDAY_COMP
