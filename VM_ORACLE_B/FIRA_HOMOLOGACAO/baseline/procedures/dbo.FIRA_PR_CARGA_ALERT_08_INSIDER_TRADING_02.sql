			, SUM(QT_NEGOCIO) QT_NEGOCIADA_COMPRA_PRE
			, SUM(VL_TOTNEG) VOLUME_COMPRA_PRE
			, AVG(QT_NEGOCIO) AVG_QT_NEGOCIADA_COMPRA_PRE
			, AVG(VL_NEGOCIO) AVG_VL_NEGOCIO_COMPRA_PRE
