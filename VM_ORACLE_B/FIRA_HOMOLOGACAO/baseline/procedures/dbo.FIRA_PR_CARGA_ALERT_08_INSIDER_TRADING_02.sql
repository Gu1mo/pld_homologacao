			, SUM(VL_TOTNEG)    VOLUME_VENDA_COMP
			, AVG(QT_NEGOCIO)   AVG_QT_NEGOCIADA_VENDA_COMP
			, AVG(VL_NEGOCIO) AVG_VL_NEGOCIO_VENDA_COMP
			, SUM(VL_NEGOCIO * QT_NEGOCIO) / SUM(QT_NEGOCIO) AVGP_VL_NEGOCIO_VENDA_COMP
