			 , A.DT_POS
			 , ISNULL(C.QT_NEGOCIADA_COMPRA_COMP,0)		AS QT_NEGOCIADA_COMPRA_COMP
			 , ISNULL(C.QT_NEGOCIO_COMPRA_COMP,0)		AS QT_NEGOCIO_COMPRA_COMP
