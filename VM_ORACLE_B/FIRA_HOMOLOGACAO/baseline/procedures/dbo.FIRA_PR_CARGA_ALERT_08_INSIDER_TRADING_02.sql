DROP TABLE IF EXISTS #COMP_CLI;
WITH COMP_C AS (		
	   SELECT CD_CLIENTE
		    , A.CD_PAPEL
		    , COUNT(NR_NEGOCIO) QT_NEGOCIO_COMPRA_COMP
			, SUM(QT_NEGOCIO) QT_NEGOCIADA_COMPRA_COMP
			, SUM(VL_TOTNEG) VOLUME_COMPRA_COMP
			, AVG(QT_NEGOCIO) AVG_QT_NEGOCIADA_COMPRA_COMP
			, AVG(VL_NEGOCIO) AVG_VL_NEGOCIO_COMPRA_COMP
			, SUM(VL_NEGOCIO * QT_NEGOCIO) / SUM(QT_NEGOCIO) AVGP_VL_NEGOCIO_COMPRA_COMP
		    , B.DT_FATO
			, B.DT_COMP
			, B.DT_PRE
			, B.DT_POS
		 FROM ST_MESA_BVSP A 
   INNER JOIN #FATO_CLI B
		   ON A.CD_PAPEL = B.CD_PAPEL
		WHERE A.DT_PERIODO >= B.DT_COMP AND A.DT_PERIODO < B.DT_PRE  --periodo comparativo
		AND CD_NATOPE = 'C'
		  AND EXISTS (SELECT 1 
						FROM #PRE_CLI C 
					   WHERE A.CD_CLIENTE = C.CD_CLIENTE 
					     AND A.CD_PAPEL   = C.CD_PAPEL )	
	 GROUP BY CD_CLIENTE
			, A.CD_PAPEL
			, B.DT_POS
			, B.DT_FATO
			, B.DT_COMP
			, B.DT_PRE
