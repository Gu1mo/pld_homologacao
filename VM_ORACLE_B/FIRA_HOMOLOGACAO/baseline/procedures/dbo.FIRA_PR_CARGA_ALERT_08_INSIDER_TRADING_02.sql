DECLARE @DT_INICIO DATE , @DT_FIM DATE , @CD_ANOMES INT

SET @CD_ANOMES = (SELECT MAX(CD_ANOMES) FROM ST_PERIODO WHERE DT_PERIODO = DATEADD(DAY,-@AUX,@PREGAO))
SET @DT_INICIO = (SELECT MIN(DT_PERIODO) fROM ST_PERIODO WHERE CD_ANOMES = @CD_ANOMES)
SET @DT_FIM	   = (SELECT MAX(DT_PERIODO) fROM ST_PERIODO WHERE CD_ANOMES = @CD_ANOMES)

DROP TABLE IF EXISTS  #FATO;	

	SELECT 
  DISTINCT A.EMPRESA								AS EMPRESA
		 , A.FATORELEVANTE							AS FATO_RELEVANTEATIVO
		 , DATA										AS DT_PERIODO
		 , ATIVO									AS ATIVO
		 , dbo.ObterDataHST(dbo.ObterDataPRE(DATA)) AS DT_COMP
		 , dbo.ObterDataPRE(DATA)					AS DT_PRE
		 , DATA										AS DT_FATO
		 , dbo.ObterDataPOS(DATA)					AS DT_POS
	 INTO #FATO
	 FROM FatosRelevantes  A
	WHERE Data >= @DT_INICIO
	  AND DATA <= @DT_FIM
 ORDER BY DATA ASC;

 -----------------------------------------------------------------------------
 DECLARE @DT_MIN_DAT SMALLDATETIME 
		,@DT_MAX_DAT SMALLDATETIME 
		,@DT_MIN_DAT_AUX SMALLDATETIME 
	    ,@DT_MAX_DAT_AUX SMALLDATETIME 

SET @DT_MIN_DAT     = (SELECT MIN(DT_COMP) FROM #FATO)
SET @DT_MAX_DAT     = (SELECT MAX(DT_POS) FROM #FATO)
SET @DT_MIN_DAT_AUX = (SELECT TOP 1 DT_PERIODO fROM ST_PERIODO WHERE DT_PERIODO < @DT_MIN_DAT ORDER BY ID_PERIODO DESC)

 

DROP TABLE IF EXISTS #BASE_MERCADO;
DROP TABLE IF EXISTS #ST_ATIVO_BOVESPA_AUX;
	 
	 SELECT 
	DISTINCT * 
		   , SUBSTRING(CODNEG,1,4) AS ATIVO 
	    INTO #ST_ATIVO_BOVESPA_AUX 
	    FROM ST_ATIVO_BOVESPA  	
	   WHERE DT_PERIODO >= @DT_MIN_DAT_AUX
	     AND DT_PERIODO <= @DT_MAX_DAT;
	
   WITH ATIVO_BVSP AS(

		   SELECT DT_PERIODO
				, LAG(DT_PERIODO,1) OVER (PARTITION BY CODNEG ORDER BY DT_PERIODO asc) AS  DT_PERIODO_ANT
				, CODNEG
				, ATIVO
				, PREABE
				, PREULT
				, LAG(PREULT,1) OVER (PARTITION BY CODNEG ORDER BY DT_PERIODO asc ) AS  PREULT_ANT
				, VOLTOT
				, TOTNEG 
			 FROM #ST_ATIVO_BOVESPA_AUX A
			WHERE EXISTS (SELECT 1 FROM #FATO B WHERE a.ativo = B.ATIVO) 

				)

		SELECT A.ATIVO
			 , B.CODNEG CD_PAPEL
			 , B.DT_PERIODO DT_PREGAO
			 , A.DT_COMP
			 , A.DT_PRE
			 , A.DT_FATO
			 , A.DT_POS
			 , DT_PERIODO_ANT DT_ANT
			 , B.PREABE
			 , B.PREULT
			 , isnull(PREULT_ANT,0) AS REULT_ANT
			 , B.VOLTOT
			 , B.TOTNEG		 
			 , ISNULL(CAST((B.PREULT / NULLIF(B.PREABE,0)) -1 AS NUMERIC(17,2)),0)  AS INTRADAY		
			 , ISNULL(CAST((B.PREABE / NULLIF(B.PREULT_ANT,0))-1 AS NUMERIC(17,2)),0)	AS INTERDAY
	      INTO #BASE_MERCADO
		  FROM #FATO A 
	INNER JOIN ATIVO_BVSP B
			ON A.ATIVO = B.ATIVO
		 WHERE a.DT_PERIODO >= @DT_MIN_DAT
	       AND a.DT_PERIODO <= @DT_MAX_DAT;

---- ativo comp
 DROP TABLE IF EXISTS #COMP;
		SELECT ATIVO
			 , CD_PAPEL
			 , DT_COMP
			 , DT_PRE
			 , DT_FATO
			 , CAST(AVG(PREABE	) AS NUMERIC(17,2))AVG_PREABE_COMP
			 , CAST(AVG(PREULT	) AS NUMERIC(17,2))AVG_PREULT_COMP
			 , CAST(AVG(VOLTOT	) AS NUMERIC(17,2))AVG_VOLTOT_COMP
			 , CAST(AVG(TOTNEG	) AS NUMERIC(17,2))AVG_TOTNEG_COMP
			 , CAST(AVG(INTRADAY) AS NUMERIC(17,2))AVG_INTRADAY_COMP		
			 , CAST(AVG(INTERDAY) AS NUMERIC(17,2))AVG_INTERDAY_COMP
		  
		  INTO #COMP
		  FROM #BASE_MERCADO
		 WHERE DT_PREGAO >= DT_COMP
		   AND DT_PREGAO <= DT_PRE
	  GROUP BY ATIVO
			 , CD_PAPEL
			 , DT_COMP
			 , DT_PRE
			 , DT_FATO

CREATE NONCLUSTERED INDEX IDX01_COMP
ON [dbo].[#COMP] ([ATIVO],[DT_FATO])
INCLUDE ([CD_PAPEL],[DT_COMP])

DROP TABLE IF EXISTS #PRE;
		SELECT ATIVO
			 , CD_PAPEL
			 , DT_PRE
			 , DT_FATO
			 , CAST(AVG(PREABE	) AS NUMERIC(17,2))AVG_PREABE_PRE
			 , CAST(AVG(PREULT	) AS NUMERIC(17,2))AVG_PREULT_PRE
			 , CAST(AVG(VOLTOT	) AS NUMERIC(17,2))AVG_VOLTOT_PRE
			 , CAST(AVG(TOTNEG	) AS NUMERIC(17,2))AVG_TOTNEG_PRE
			 , CAST(AVG(INTRADAY) AS NUMERIC(17,2))AVG_INTRADAY_PRE		
			 , CAST(AVG(INTERDAY) AS NUMERIC(17,2))AVG_INTERDAY_PRE
		  
		  INTO #PRE
		  FROM #BASE_MERCADO
		 WHERE DT_PREGAO >= DT_PRE 
		   AND DT_PREGAO < DT_FATO
	  GROUP BY ATIVO
			 , CD_PAPEL
			 , DT_PRE
			 , DT_FATO
			
DROP TABLE IF EXISTS #POS;
		SELECT ATIVO
			 , CD_PAPEL			 
			 , DT_FATO
			 , DT_POS
			 , CAST(AVG(PREABE	) AS NUMERIC(17,2))AVG_PREABE_POS
			 , CAST(AVG(PREULT	) AS NUMERIC(17,2))AVG_PREULT_POS
			 , CAST(AVG(VOLTOT	) AS NUMERIC(17,2))AVG_VOLTOT_POS
			 , CAST(AVG(TOTNEG	) AS NUMERIC(17,2))AVG_TOTNEG_POS
			 , CAST(AVG(INTRADAY) AS NUMERIC(17,2))AVG_INTRADAY_POS		
			 , CAST(AVG(INTERDAY) AS NUMERIC(17,2))AVG_INTERDAY_POS
		  
		  INTO #POS
		  FROM #BASE_MERCADO
		 WHERE DT_PREGAO >= DT_FATO
		   AND DT_PREGAO <= DT_POS
	  GROUP BY ATIVO
			 , CD_PAPEL
			 , DT_POS
			 , DT_FATO

			CREATE INDEX IDX_COMP ON #COMP (ATIVO,DT_FATO,CD_PAPEL)
			CREATE INDEX IDX_PRE  ON #PRE (ATIVO,DT_FATO,CD_PAPEL)
