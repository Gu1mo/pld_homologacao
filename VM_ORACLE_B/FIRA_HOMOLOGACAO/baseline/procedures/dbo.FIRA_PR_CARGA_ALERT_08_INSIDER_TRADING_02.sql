			, SUM(VL_TOTNEG)    VOLUME_VENDA_PRE
			, AVG(QT_NEGOCIO)   AVG_QT_NEGOCIADA_VENDA_PRE
			, AVG(VL_NEGOCIO) AVG_VL_NEGOCIO_VENDA_PRE
			, SUM(VL_NEGOCIO * QT_NEGOCIO) / SUM(QT_NEGOCIO) AVGP_VL_NEGOCIO_VENDA_PRE
		    , B.DT_FATO		    
