	UNION
	SELECT CD_CLIENTE,CD_PAPEL,DT_COMP,DT_PRE,DT_FATO,DT_POS FROM PRE_V

	)	
	
		SELECT A.CD_CLIENTE
			 , A.CD_PAPEL
			 , A.DT_COMP
			 , A.DT_PRE
			 , A.DT_FATO
			 , A.DT_POS
			 , ISNULL(C.QT_NEGOCIADA_COMPRA_PRE,0)	   AS QT_NEGOCIADA_COMPRA_PRE
			 , ISNULL(C.QT_NEGOCIO_COMPRA_PRE,0)	   AS QT_NEGOCIO_COMPRA_PRE
			 , ISNULL(C.VOLUME_COMPRA_PRE,0)		   AS VOLUME_COMPRA_PRE
			 , ISNULL(C.AVG_QT_NEGOCIADA_COMPRA_PRE,0) AS AVG_QT_NEGOCIADA_COMPRA_PRE
			 , ISNULL(C.AVG_VL_NEGOCIO_COMPRA_PRE,0)   AS AVG_VL_NEGOCIO_COMPRA_PRE
			 , ISNULL(V.QT_NEGOCIADA_VENDA_PRE,0)	   AS QT_NEGOCIADA_VENDA_PRE
			 , ISNULL(V.QT_NEGOCIO_VENDA_PRE,0)		   AS QT_NEGOCIO_VENDA_PRE
			 , ISNULL(V.VOLUME_VENDA_PRE,0)			   AS VOLUME_VENDA_PRE
			 , ISNULL(V.AVG_QT_NEGOCIADA_VENDA_PRE,0)  AS AVG_QT_NEGOCIADA_VENDA_PRE
			 , ISNULL(V.AVG_VL_NEGOCIO_VENDA_PRE,0)    AS AVG_VL_NEGOCIO_VENDA_PRE
			 , ISNULL(C.AVGP_VL_NEGOCIO_COMPRA_PRE,0)  AS AVGP_VL_NEGOCIO_COMPRA_PRE
			 , ISNULL(V.AVGP_VL_NEGOCIO_VENDA_PRE,0)   AS AVGP_VL_NEGOCIO_VENDA_PRE
		 INTO #PRE_CLI
		 FROM PRE A
	LEFT JOIN PRE_C C
		   ON A.CD_CLIENTE = C.CD_CLIENTE
		  AND A.CD_PAPEL = C.CD_PAPEL
		  AND A.DT_FATO = C.DT_FATO
		  AND A.DT_PRE  = C.DT_PRE
	LEFT JOIN PRE_V V 
		   ON  A.CD_CLIENTE = V.CD_CLIENTE
		  AND A.CD_PAPEL = V.CD_PAPEL
		  AND A.DT_FATO = V.DT_FATO	
		  AND A.DT_PRE = V.DT_PRE

