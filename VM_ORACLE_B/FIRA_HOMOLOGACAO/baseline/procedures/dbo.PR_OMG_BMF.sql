CREATE PROCEDURE [dbo].[PR_OMG_BMF] (
    @INICIO       SMALLDATETIME,
    @FIM          SMALLDATETIME,
    @CD_CLIENTE   VARCHAR(160),
    @QTDPORPAGINA INT,
    @PAGINA       INT
)
