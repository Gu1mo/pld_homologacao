AS

--DECLARE @INICIO SMALLDATETIME , @FIM SMALLDATETIME, @CD_CLIENTE INT , @PAGINA       INT     ,@QTDPORPAGINA INT
--set @inicio='20251201'
--set @fim='20251231'
