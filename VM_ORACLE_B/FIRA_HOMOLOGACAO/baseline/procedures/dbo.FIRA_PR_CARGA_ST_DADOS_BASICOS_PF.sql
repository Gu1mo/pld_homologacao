	J.NM_GRUPO, 
	K.NM_ASSESSOR,
	B.VL_OPERACIONAL1, 
	B.VL_OPERACIONAL2, 
	B.VL_OPERACIONAL3, 
	B.VL_CAPACIDADE_FIN , 
	L.DS_ATIV, 
	F.DS_CARGO,
	DT_VL_OPERACIONAL,
	E.TP_CLIENTE,
	K.NM_RESU_ASSES,
	A.IND_CAD_SIMP,
	h.IN_PRINCIPAL,
	D.IN_PROCUR,
	A.DT_ULT_OPER,
	CASE 
		WHEN D.DT_VALIDADE < CONVERT(VARCHAR,''17530101'',103) THEN CONVERT(VARCHAR,''99991231'',103)
		ELSE D.DT_VALIDADE 
	END AS DT_VALIDADE,
	NM_COMPL_NOME,---inserido 17.11.2023 devido suitability
	NULL AS CPFCNPJ,
	null AS IN_QUALIFICADO,
	CD_CNPJ_EMPRESA

FROM TSCCLIBOL A (NOLOCK)
LEFT OUTER  JOIN TSCCLIGER B (NOLOCK)
	ON  A.CD_CPFCGC = B.CD_CPFCGC
	AND A.DT_NASC_FUND = B.DT_NASC_FUND
	AND A.CD_CON_DEP = B.CD_CON_DEP

LEFT OUTER JOIN TSCENDE C  (NOLOCK)
	ON A.CD_CPFCGC =  C.CD_CPFCGC 
	AND A.DT_NASC_FUND = C.DT_NASC_FUND 
	AND A.CD_CON_DEP = C.CD_CON_DEP 

LEFT OUTER JOIN TSCDOCS D  	 (NOLOCK)
	ON A.CD_CPFCGC = D.CD_CPFCGC  	
    AND A.DT_NASC_FUND = D.DT_NASC_FUND  	
    AND A.CD_CON_DEP = D.CD_CON_DEP 

LEFT OUTER JOIN TSCTIPCLI E (NOLOCK)
	ON  B.TP_CLIENTE = E.TP_CLIENTE

LEFT OUTER JOIN TSCCLICOMP F (NOLOCK)
	ON A.CD_CPFCGC = F.CD_CPFCGC
	AND A.DT_NASC_FUND = F.DT_NASC_FUND
	AND A.CD_CON_DEP = F.CD_CON_DEP

