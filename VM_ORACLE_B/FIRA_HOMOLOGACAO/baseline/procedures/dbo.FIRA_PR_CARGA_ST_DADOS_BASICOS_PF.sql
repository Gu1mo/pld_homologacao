DECLARE @sql nvarchar(max) = N'
INSERT INTO ST_DADOS_BASICOS_PF	
(
	 NM_CLIENTE,CD_CLIENTE,CD_CPFCGC,DT_CRIACAO,DT_ATUALIZ,NM_LOGRADOURO
	,NR_PREDIO,NM_COMP_ENDE,NM_BAIRRO,NM_CIDADE,SG_ESTADO,SG_PAIS,NM_E_MAIL
