	ON F.CD_NACION = G.CD_NACION

LEFT OUTER JOIN TSCEMITORDEM H  (NOLOCK)
	ON A.CD_CPFCGC = H.CD_CPFCGC
	AND A.DT_NASC_FUND = H.DT_NASC_FUND
	AND A.CD_CON_DEP = H.CD_CON_DEP

LEFT OUTER JOIN TSCCONDEP I (NOLOCK)
	ON A.CD_CON_DEP = I.CD_CON_DEP

LEFT OUTER JOIN TSCCLIGRUPO J (NOLOCK)
	ON B.CD_GRUPO = J.CD_GRUPO

LEFT OUTER JOIN TSCASSES K  (NOLOCK)
	ON A.CD_ASSESSOR = K.CD_ASSESSOR

LEFT OUTER JOIN TSCATIV L   (NOLOCK)
	ON F.CD_ATIV = L.CD_ATIV 

LEFT OUTER JOIN TSCEMAIL M (NOLOCK)
	ON A.CD_CPFCGC = M.CD_CPFCGC
	AND A.DT_NASC_FUND = M.DT_NASC_FUND

				
WHERE B.TP_PESSOA = ''F''

 
INSERT INTO ST_DADOS_BASICOS_PF	
(
	 NM_CLIENTE,CD_CLIENTE,CD_CPFCGC,DT_CRIACAO,DT_ATUALIZ,NM_LOGRADOURO
	,NR_PREDIO,NM_COMP_ENDE,NM_BAIRRO,NM_CIDADE,SG_ESTADO,SG_PAIS,NM_E_MAIL
	,IN_PESS_VINC,DT_NASC_FUND,DS_TIPO_CLIENTE,NM_PAI,NM_MAE,NM_CONJUGE
	,NR_TELEFONE,DS_NACION,IN_POLITICO_EXP,NM_EMIT_ORDEM,CD_CPFCGC_EMIT
	,CD_DOC_IDENT_EMIT,EMISSOR_PRINCIPAL,CD_SISTEMA,ENDE_SEQ,MAIL_SEQ
	,CD_ASSESSOR,CD_CON_DEP,DS_CON_DEP,IN_CONTA_INV,IN_SITUAC,cd_Cep
	,CD_DDD_TEL,TP_SITUAC,nm_grupo,NM_ASSESSOR,VL_OPERACIONAL1,VL_OPERACIONAL2
	,VL_OPERACIONAL3,VL_CAPACIDADE_FIN,DS_ATIV,DS_CARGO,DT_ATUALIZ_SALARIO
	,TP_CLIENTE,NM_RESU_ASSES,IND_CAD_SIMP,IN_PRINCIPAL,IN_PROCUR,DT_ULT_OPER
	,DT_VALIDADE,NM_COMPL_NOME,CPFCNPJ,IN_QUALIFICADO,CD_CNPJ_EMPRESA
)
SELECT  
	B.NM_CLIENTE,
	A.CD_CLIENTE,
	A.CD_CPFCGC,
	B.DT_CRIACAO,
	B.DT_ATUALIZ,
	C.NM_LOGRADOURO,
	C.NR_PREDIO,
	C.NM_COMP_ENDE,
	C.NM_BAIRRO,
	C.NM_CIDADE,
	C.SG_ESTADO, 
	C.SG_PAIS, 
	ISNULL(M.NM_E_MAIL, C.NM_E_MAIL) NM_E_MAIL,
	B.IN_PESS_VINC,
	B.DT_NASC_FUND,
	E.DS_TIPO_CLIENTE,
	F.NM_PAI,
	F.NM_MAE,
	F.NM_CONJUGE,
	C.NR_TELEFONE,
	G.DS_NACION,
	B.IN_POLITICO_EXP,
	H.NM_EMIT_ORDEM,
	H.CD_CPFCGC_EMIT,
	H.CD_DOC_IDENT_EMIT,
	H.IN_PRINCIPAL AS EMISSOR_PRINCIPAL,
	H.CD_SISTEMA,
	NULL AS ENDE_SEQ,
	NULL AS MAIL_SEQ,
	NULL AS CD_ASSESSOR,
	A.CD_CON_DEP,
	I.DS_CON_DEP,
	NULL AS IN_CONTA_INV,
	NULL AS IN_SITUAC,
	CAST(C.CD_CEP AS VARCHAR) +''-''+CAST(C.CD_CEP_EXT AS VARCHAR) AS CD_CEP,
	C.CD_DDD_TEL,
	CASE 
		WHEN B.TP_SITUAC = ''AT'' THEN ''ATIVO''
		WHEN B.TP_SITUAC = ''IN'' THEN ''INATIVO''
		WHEN B.TP_SITUAC = ''BL'' THEN ''BLOQUEADO''
		WHEN B.TP_SITUAC = ''EN'' THEN ''ENCERRADO''
	ELSE ''OUTROS'' END TP_SITUAC,
	J.NM_GRUPO, 
	K.NM_ASSESSOR,
	B.VL_OPERACIONAL1, 
	B.VL_OPERACIONAL2, 
	B.VL_OPERACIONAL3, 
	B.VL_CAPACIDADE_FIN , 
	L.DS_ATIV, 
	F.DS_CARGO,
	DT_VL_OPERACIONAL,
	E.TP_CLIENTE,
	K.NM_RESU_ASSES,
	NULL AS IND_CAD_SIMP,
	h.IN_PRINCIPAL,
	D.IN_PROCUR,
	NULL AS DT_ULT_OPER,
	CASE 
		WHEN D.DT_VALIDADE < CONVERT(VARCHAR,''17530101'',103) THEN CONVERT(VARCHAR,''99991231'',103)
		ELSE D.DT_VALIDADE 
	END AS DT_VALIDADE,
    null as NM_COMPL_NOME,
	NULL AS CPFCNPJ,
	null AS IN_QUALIFICADO,
	CD_CNPJ_EMPRESA

FROM TSCCLICC A (NOLOCK)
LEFT OUTER  JOIN TSCCLIGER B (NOLOCK)
	ON  A.CD_CPFCGC = B.CD_CPFCGC
	AND A.DT_NASC_FUND = B.DT_NASC_FUND
	AND A.CD_CON_DEP = B.CD_CON_DEP

LEFT OUTER JOIN TSCENDE C  (NOLOCK)
	ON A.CD_CPFCGC =  C.CD_CPFCGC 
	AND A.DT_NASC_FUND = C.DT_NASC_FUND 
	AND A.CD_CON_DEP = C.CD_CON_DEP 

LEFT OUTER JOIN TSCDOCS D  	 (NOLOCK)
	ON A.CD_CPFCGC = D.CD_CPFCGC  	
    AND A.DT_NASC_FUND = D.DT_NASC_FUND  	
    AND A.CD_CON_DEP = D.CD_CON_DEP 

LEFT OUTER JOIN TSCTIPCLI E (NOLOCK)
	ON  B.TP_CLIENTE = E.TP_CLIENTE

LEFT OUTER JOIN TSCCLICOMP F (NOLOCK)
	ON A.CD_CPFCGC = F.CD_CPFCGC
	AND A.DT_NASC_FUND = F.DT_NASC_FUND
	AND A.CD_CON_DEP = F.CD_CON_DEP

LEFT OUTER JOIN TSCNACION G (NOLOCK)
	ON F.CD_NACION = G.CD_NACION

LEFT OUTER JOIN TSCEMITORDEM H (NOLOCK)
	ON A.CD_CPFCGC = H.CD_CPFCGC
	AND A.DT_NASC_FUND = H.DT_NASC_FUND
	AND A.CD_CON_DEP = H.CD_CON_DEP

LEFT OUTER JOIN TSCCONDEP I (NOLOCK)
	ON A.CD_CON_DEP = I.CD_CON_DEP

LEFT OUTER JOIN TSCCLIGRUPO J (NOLOCK)
	ON B.CD_GRUPO = J.CD_GRUPO

LEFT OUTER JOIN TSCASSES K  (NOLOCK)
	ON B.CD_ASSESSOR = K.CD_ASSESSOR

LEFT OUTER JOIN TSCATIV L   (NOLOCK)
	ON F.CD_ATIV = L.CD_ATIV 

LEFT OUTER JOIN TSCEMAIL M (NOLOCK)
	ON A.CD_CPFCGC = M.CD_CPFCGC
	AND A.DT_NASC_FUND = M.DT_NASC_FUND
	
 
				
WHERE B.TP_PESSOA = ''F''
AND A.CD_CLIENTE NOT IN (SELECT DISTINCT CD_CLIENTE FROM ST_DADOS_BASICOS_PF (NOLOCK))
 
 update ST_DADOS_BASICOS_PF
 set cpfcnpj = dbo.FORMATAR_CPF(CD_CPFCGC)

 	 DROP TABLE IF EXISTS #Q
	 SELECT CD_CLIENTE INTO #Q  FROM ST_DADOS_BASICOS_PF
	 WHERE IN_QUALIFICADO IS NULL

	 DROP TABLE IF EXISTS #V
	 SELECT A.CD_CLIENTE,IN_QUALIFICADO INTO #V FROM ST_V_TBOMOVCL A
	 JOIN #Q B ON A.CD_CLIENTE=B.CD_CLIENTE
	 
	 UPDATE A
	 SET A.IN_QUALIFICADO = B.IN_QUALIFICADO
	 FROM ST_DADOS_BASICOS_PF A JOIN #V B ON A.CD_CLIENTE=B.CD_CLIENTE
';
EXEC sys.sp_executesql @sql;
