	,VL_OPERACIONAL3,VL_CAPACIDADE_FIN,DS_ATIV,DS_CARGO,DT_ATUALIZ_SALARIO
	,TP_CLIENTE,NM_RESU_ASSES,IND_CAD_SIMP,IN_PRINCIPAL,IN_PROCUR,DT_ULT_OPER
	,DT_VALIDADE,NM_COMPL_NOME,CPFCNPJ,IN_QUALIFICADO,CD_CNPJ_EMPRESA
)
	
SELECT  
	B.NM_CLIENTE,
	A.CD_CLIENTE,
	A.CD_CPFCGC,
	B.DT_CRIACAO,
	B.DT_ATUALIZ,
	C.NM_LOGRADOURO,
	C.NR_PREDIO,
	C.NM_COMP_ENDE,
	C.NM_BAIRRO,
	C.NM_CIDADE,
	C.SG_ESTADO, 
	C.SG_PAIS, 
	ISNULL(M.NM_E_MAIL, C.NM_E_MAIL) NM_E_MAIL,
	B.IN_PESS_VINC,
	B.DT_NASC_FUND,
	E.DS_TIPO_CLIENTE,
	F.NM_PAI,
	F.NM_MAE,
	F.NM_CONJUGE,
	C.NR_TELEFONE,
	G.DS_NACION,
	B.IN_POLITICO_EXP,
	H.NM_EMIT_ORDEM,
	H.CD_CPFCGC_EMIT,
	H.CD_DOC_IDENT_EMIT,
