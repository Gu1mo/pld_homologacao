        0 CHURNING_01, 0 OMC_01, 0 OMC_BMF_01, 0 LAYERING_01, 0 SPOOFING_01,0 TRANSFERENCIA_FINANCEIRA_02, 0 TRANSFERENCIA_01, 0 INSIDER_TRADING_BOVESPA, 
        0 PATRIMONIO_CUSTODIA, 0 PATRIMONIO_NETTING, 0 PATRIMONIO_MOVCC, 0 PATRIMONIO_TRANSF_CUST,0 SWING_ATIVO_BMF,0 SWING_ATIVO_BVSP,0 MONEYPASS_BOVESPA, 0 MONEYPASS_BMF
        
        ,0 CHURNING_02,0 INSIDER_TRADING_BOVESPA_02, 0 LISTA_ATENCAO, 0 RANKING_DAYTRADE_BVSP, 0 RANKING_DAYTRADE_BMF, 0 OSCILACAO
        FROM(
        SELECT DISTINCT DATA,CD_CLIENTE
        FROM ST_ALERT_AML_CORRETORA_BMF INNER JOIN ST_PERIODO ON DATA = DT_PERIODO
        WHERE DT_PERIODO >= EOMONTH(@DT_PERIODO,-6) AND DT_PERIODO < @DT_PERIODO) X
        GROUP BY DATA,CD_CLIENTE


        UNION ALL -- AML_CORRETORA
        SELECT DISTINCT DATA,CD_CLIENTE, 0 AML_CORRETORA_BMF, COUNT(DISTINCT 1)  AML_CORRETORA, 0  ATULIZACAO_CADASTRAL_01, 0  BMF_AML, 0  BOVESPA_AML, 0  DAYTRADE_ATIVO_BMF, 0  
        DAYTRADE_ATIVO_BOVESPA, 0  DAYTRADE_BMF_01, 0  DAYTRADE_BOVESPA_01, 0  MEDIA_BMF_01, 0  MEDIA_BOVESPA_01, 
        0  MUDANCA_REPENTINA_01, 0  PROCURADOR_01, 0  SWING_BMF, 0  SWING_BOVESPA, 0  TRANSFERENCIA_FINANCEIRA_01, 0 PATRIMONIO_01,
