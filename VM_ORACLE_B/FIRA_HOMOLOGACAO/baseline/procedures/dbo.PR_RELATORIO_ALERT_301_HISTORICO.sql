                MAX(T1.DS_ATIV) AS "PROFISSÃO",
                ISNULL(MAX(T1.RISCO),'OUTROS') AS "PROFISSÃO DE RISCO",
                ISNULL(MAX(TT.RISCO_FINAL),'') AS "SCORE RISCO",    
