        0  MUDANCA_REPENTINA_01, 0  PROCURADOR_01, 0  SWING_BMF, 0  SWING_BOVESPA, 0  TRANSFERENCIA_FINANCEIRA_01, 0 PATRIMONIO_01, 0 CHURNING_01
