6 MESES DOS CLIENTES.
****************************************/

--DECLARE @CD_ANO INT, @DS_MES  VARCHAR(20) , @CD_CLIENTE VARCHAR(160),@QTDPORPAGINA INT = '100000', @PAGINA INT = 1;
--SET @CD_ANO = 2024 
--SET @DS_MES = 'SETEMBRO'
--SET @CD_CLIENTE ='100396'

DECLARE @DT_PERIODO SMALLDATETIME
SET @DT_PERIODO = (SELECT MAX(DT_PERIODO) FROM St_PERIODO WHERE CD_ANO = @CD_ANO AND DS_MES = @DS_MES)


DECLARE @WV_RISCO_FINAL TABLE ([Data] VARCHAR(20), [Cód. do Cliente] int,[Nome do Cliente] nvarchar(160),[RISCO_FINAL] varchar(5))
INSERT INTO @WV_RISCO_FINAL SELECT [Data],[Cód. do Cliente],[Nome do Cliente],[RISCO_FINAL] FROM WV_RISCO_FINAL
--DROP TABLE IF EXISTS #WV_RISCO_FINAL
--SELECT * INTO #WV_RISCO_FINAL FROM WV_RISCO_FINAL

---FRONTEIRA
DECLARE @FRONTEIRA TABLE ([Cidade] varchar(50),[UF] varchar(4))
INSERT INTO @FRONTEIRA
SELECT DISTINCT DBO.FN_FORMATAR_TEXTO(NOME)[Cidade],
SUBSTRING(
        Detalhes, 
        CHARINDEX('SIGLA_UF:', Detalhes) + LEN('SIGLA_UF:'), 
        2
    ) AS [UF] FROM ListaAtencao 
WHERE IdSublista = 47
AND  CHARINDEX('SIGLA_UF:', Detalhes) > 0


SELECT 
    CASE 
    WHEN ( SUM(BOVESPA_AML)       >0 
        OR SUM(BMF_AML)           >0 
        OR SUM(SPOOFING_01)       >0 
        OR SUM(LAYERING_01)       >0 
        OR SUM(MONEYPASS_BOVESPA) >0
        OR SUM(MONEYPASS_BMF)     >0
		OR SUM(OSCILACAO)     >0) 
    THEN 'VERMELHO'
    WHEN (  SUM(BOVESPA_AML)=0 
        AND SUM(BMF_AML)    =0 
        AND SUM(SPOOFING_01)=0 
        AND SUM(LAYERING_01)=0) 
        AND (      SUM(DAYTRADE_BOVESPA_01)         >0 
                OR SUM(DAYTRADE_BMF_01)             >0 
                OR SUM(DAYTRADE_ATIVO_BOVESPA)      >0 
                OR SUM(DAYTRADE_ATIVO_BMF)          >0 
                OR SUM(AML_CORRETORA)               >0 
                OR SUM(AML_CORRETORA_BMF)           >0 
                OR SUM(SWING_BOVESPA)               >0 
                OR SUM(SWING_BMF)                   >0 
                OR SUM(SWING_ATIVO_BMF)             >0
                OR SUM(SWING_ATIVO_BVSP)            >0 
                --OR SUM(CHURNING_01)                   >0
                OR SUM(CHURNING_02)                 >0
                OR SUM(ATULIZACAO_CADASTRAL_01)     >0 
                --OR SUM(INSIDER_TRADING_BOVESPA)       >0 
                OR SUM(INSIDER_TRADING_BOVESPA_02)  >0 
                OR SUM(TRANSFERENCIA_FINANCEIRA_01) >0 
                OR SUM(TRANSFERENCIA_FINANCEIRA_02) >0
				OR SUM(OSCILACAO) >0	)  
        THEN 'AMARELO'  
        WHEN  ( SUM(BOVESPA_AML)                =0 
            AND SUM(BMF_AML)                    =0 
            AND SUM(SPOOFING_01)                =0 
            AND SUM(LAYERING_01)                =0 
            AND SUM(DAYTRADE_BOVESPA_01)        =0 
            OR SUM(DAYTRADE_BMF_01)             =0 
            OR  SUM(DAYTRADE_ATIVO_BOVESPA)     =0 
            OR SUM(DAYTRADE_ATIVO_BMF)          =0 
            OR SUM(AML_CORRETORA)               =0 
            OR SUM(AML_CORRETORA_BMF)           =0 
            OR SUM(SWING_BOVESPA)               =0 
            OR SUM(SWING_ATIVO_BMF)             =0 
            OR SUM(SWING_ATIVO_BVSP)            =0 
            OR SUM(SWING_BMF)                   =0 
            --OR SUM(CHURNING_01)                   =0 
            OR SUM(CHURNING_02)                 =0 
            OR SUM(ATULIZACAO_CADASTRAL_01)     =0 
            --OR SUM(INSIDER_TRADING_BOVESPA)       =0 
            OR SUM(INSIDER_TRADING_BOVESPA_02)      =0
            OR SUM(TRANSFERENCIA_FINANCEIRA_01) =0 
            OR SUM(TRANSFERENCIA_FINANCEIRA_02) =0)  
           AND (   SUM(PATRIMONIO_CUSTODIA)     >0 
                OR SUM(PATRIMONIO_NETTING)      >0 
                OR SUM(PATRIMONIO_MOVCC)        >0
                OR SUM(PATRIMONIO_TRANSF_CUST)  >0 
                OR SUM(OMC_BMF_01)              >0 
                OR SUM(OMC_01)                  >0 
                OR SUM(PROCURADOR_01)           >0 
                OR SUM(PATRIMONIO_01)           >0
				OR SUM(OSCILACAO)           >0)
        THEN 'LARANJA' 
        ELSE 'VERDE' 
        END  AS "ANALISE",
        CONCAT(CASE WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 1 THEN 'JANEIRO' 
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 2 THEN 'FEVEREIRO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 3 THEN 'MARÇO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 4 THEN 'ABRIL'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 5 THEN 'MAIO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 6 THEN 'JUNHO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 7 THEN 'JULHO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 8 THEN 'AGOSTO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 9 THEN 'SETEMBRO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 10 THEN 'OUTUBRO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 11 THEN 'NOVEMBRO'
                    WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 12 THEN 'DEZEMBRO' END,' - ',
				CASE WHEN MONTH(EOMONTH(@DT_PERIODO,-6)) = 1 THEN 'JANEIRO' 
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 2 THEN 'FEVEREIRO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 3 THEN 'MARÇO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 4 THEN 'ABRIL'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 5 THEN 'MAIO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 6 THEN 'JUNHO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 7 THEN 'JULHO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 8 THEN 'AGOSTO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 9 THEN 'SETEMBRO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 10 THEN 'OUTUBRO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 11 THEN 'NOVEMBRO'
                            WHEN MONTH(EOMONTH(@DT_PERIODO,-1)) = 12 THEN 'DEZEMBRO' END +' / '+ CAST(YEAR(EOMONTH(@DT_PERIODO,-1)) AS VARCHAR))AS Referencia,

                Y.CD_CLIENTE AS "Cód. Cliente",
                T1.NM_CLIENTE AS "NOME DO CLIENTE",
                MAX(T1.DS_NACION) AS "NACIONALIDADE",
                CASE WHEN LEN(T1.CD_CPFCGC) > 11 THEN dbo.formatar_cnpj(t1.cd_cpfcgc) ELSE dbo.formatar_cpf(t1.cd_cpfcgc)  END AS "CPF/CNPJ", 
                CASE WHEN LEN(T1.CD_CPFCGC) > 11 THEN 'PJ' ELSE 'PF ' END AS "PF / PJ",             
                MAX(T1.IDADE) AS "IDADE",
                MAX(T1.DS_TIPO_CLIENTE) AS "INVESTIDOR",                
                FORMAT(T1.DT_CRIACAO,'d','PT-BR') AS "DATA DE CRIAÇÃO",
				CASE WHEN F.CIDADE IS NOT NULL THEN 'SIM'
				ELSE 'NÃO'
				END AS "FRONTEIRA",
                CASE WHEN T1.IN_POLITICO_EXP = 'S' THEN 'SIM'
                WHEN T1.IN_POLITICO_EXP = 'N' THEN 'NÃO'
                ELSE  '' END AS "PEP SINACOR",
                CASE WHEN T1.IN_PESS_VINC = 'S' THEN 'SIM'
                WHEN T1.IN_PESS_VINC = 'N' THEN 'NÃO'
                ELSE  '' END AS "PESSOA VINCULADA",
